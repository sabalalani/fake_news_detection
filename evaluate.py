# MAIN EVALUATION LOOP
# =====================================================

train_results = []
test_results  = []

roc_data = {}   # Dictionary array mapping parameters for final ROC curve plotting
pr_data  = {}   # Dictionary array mapping parameters for final PR curve plotting

best_model_name = None
best_f1         = 0
best_model_obj  = None

# Loop comprehensively over the registered serial model paths dict objects
for model_name, model_path in MODEL_PATHS.items():

    # Safety check to prevent structural path file missing runtime errors
    if not os.path.exists(model_path):
        print(f"\n  Skipping {model_name} — file not found: {model_path}")
        continue

    print(f"\nEvaluating: {model_name}...")
    model = pickle.load(open(model_path, "rb"))

    # Compute comprehensive evaluation metrics structures over validation sets
    train_m = compute_all_metrics(model, X_train, y_train, "TRAIN")
    test_m  = compute_all_metrics(model, X_test,  y_test,  "TEST")

    train_m["model"] = model_name
    test_m["model"]  = model_name

    train_results.append(train_m)
    test_results.append(test_m)

    print_full_report(model, model_name, train_m, test_m)

    # =====================================================
    # CONFUSION MATRIX PLOT (Unified Path Alignment Fix)
    # =====================================================
    preds = model.predict(X_test)
    cm    = confusion_matrix(y_test, preds)
    fig, ax = plt.subplots(figsize=(5, 4))
    disp = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=["Fake", "Real"]
    )
    # Draw native non-colorbar blue heatmaps for clean publication styling
    disp.plot(ax=ax, colorbar=False, cmap="Blues")
    ax.set_title(f"{model_name}\nConfusion Matrix (Test set)", fontsize=10)
    plt.tight_layout()
    safe_name = model_name.lower().replace(" ", "_")
    # Save using short '_cm.png' schema matching train_models.py
    plt.savefig(f"results/{safe_name}_cm.png", dpi=150)
    plt.close()

    # Store individual models curve array thresholds data if decision functions exist
    scores = get_scores(model, X_test)
    if scores is not None:
        fpr, tpr, _ = roc_curve(y_test, scores)
        prec_c, rec_c, _ = precision_recall_curve(y_test, scores)
        roc_data[model_name] = (fpr, tpr, test_m["roc_auc"])
        pr_data[model_name]  = (rec_c, prec_c, test_m["pr_auc"])

    # Log champion validation attributes
    if test_m["f1"] > best_f1:
        best_f1         = test_m["f1"]
        best_model_name = model_name
        best_model_obj  = model


