def get_scores(model, X):
    """
    Return probability/decision scores for ROC/PR curves.
    Handles continuous decision space tracking variations across model types.
    """
    try:
        # Probabilistic classifiers output continuous classification ratios
        if hasattr(model, "predict_proba"):
            return model.predict_proba(X)[:, 1]
        # Hyper-plane margin boundaries classifiers output continuous distance floats
        else:
            return model.decision_function(X)
    except Exception:
        return None


def compute_all_metrics(model, X, y_true, split="TEST"):
    """Full metric set for one model on one split."""
    preds  = model.predict(X)
    scores = get_scores(model, X)

    # Compute macro global evaluation summary parameters
    acc   = accuracy_score(y_true, preds)
    prec  = precision_score(y_true, preds, zero_division=0)
    rec   = recall_score(y_true, preds, zero_division=0)
    f1    = f1_score(y_true, preds, zero_division=0)
    # MCC serves as a balanced evaluation summary tracking all 4 quadrants of the confusion matrix symmetrically
    mcc   = matthews_corrcoef(y_true, preds)

    # Compute un-averaged per-class precision / recall / f1 vectors
    prec_cls = precision_score(y_true, preds, average=None, zero_division=0)
    rec_cls  = recall_score(y_true, preds, average=None, zero_division=0)
    f1_cls   = f1_score(y_true, preds, average=None, zero_division=0)

    auc_roc = None
    auc_pr  = None
    if scores is not None:
        try:
            # ROC-AUC tracks TPR vs FPR trading parameters under dynamic decision thresholds
            auc_roc = roc_auc_score(y_true, scores)
            # PR-AUC (Average Precision) serves as a superior indicator under high class/feature sparsity drops
            auc_pr  = average_precision_score(y_true, scores)
        except Exception:
            pass

    return {
        "split"        : split,
        "accuracy"     : round(acc,  4),
        "precision"    : round(prec, 4),
        "recall"       : round(rec,  4),
        "f1"           : round(f1,   4),
        "mcc"          : round(mcc,  4),
        "roc_auc"      : round(auc_roc, 4) if auc_roc else None,
        "pr_auc"       : round(auc_pr,  4) if auc_pr  else None,
        # Parse localized per-class metrics splits
        "prec_fake"    : round(prec_cls[0], 4),
        "prec_real"    : round(prec_cls[1], 4),
        "rec_fake"     : round(rec_cls[0],  4),
        "rec_real"     : round(rec_cls[1],  4),
        "f1_fake"      : round(f1_cls[0],   4),
        "f1_real"      : round(f1_cls[1],   4),
    }


def print_full_report(model, model_name, train_m, test_m):
    """Generates highly readable comparative terminal logging telemetry sheets."""
    print(f"\n{'='*65}")
    print(f"  {model_name}")
    print(f"{'='*65}")

    # Display an inline train vs test metrics table tracking operational variance gap drops
    print(f"\n  {'Metric':<16}  {'TRAIN':>10}  {'TEST':>10}  {'Gap':>10}")
    print(f"  {'-'*52}")
    for key in ["accuracy", "precision", "recall", "f1", "mcc", "roc_auc", "pr_auc"]:
        tr = train_m.get(key)
        te = test_m.get(key)
        if tr is not None and te is not None:
            gap  = round(tr - te, 4)
            # Alert user if performance delta exceeds standard 5% variance threshold parameters
            flag = "  ⚠" if gap > 0.05 else ""
            print(f"  {key:<16}  {tr:>10}  {te:>10}  {gap:>+9.4f}{flag}")
        else:
            print(f"  {key:<16}  {'N/A':>10}  {'N/A':>10}")

    # Output detailed target class resolution boundaries
    print(f"\n  Per-class metrics (TEST):")
    print(f"  {'Class':<12}  {'Precision':>10}  {'Recall':>10}  {'F1':>10}")
    print(f"  {'-'*46}")
    print(f"  {'Fake (0)':<12}  {test_m['prec_fake']:>10}  {test_m['rec_fake']:>10}  {test_m['f1_fake']:>10}")
    print(f"  {'Real (1)':<12}  {test_m['prec_real']:>10}  {test_m['rec_real']:>10}  {test_m['f1_real']:>10}")

    # Ingest the standard sklearn classification report structure with support metadata
    preds = model.predict(X_test)
    print(f"\n  Classification Report (TEST):")
    report = classification_report(
        y_test, preds,
        target_names=["Fake (0)", "Real (1)"],
        digits=4
    )
    for line in report.splitlines():
        print(f"    {line}")


