# CROSS-VALIDATION HELPER
# =====================================================

def cross_val_summary(model, model_name, cv=5):
    """
    Runs stratified 5-fold CV and prints mean ± std for
    accuracy, precision, recall, f1.
    """
    # Stratified folds protect class balances across every cross-validation slice
    skf = StratifiedKFold(n_splits=cv, shuffle=True, random_state=42)
    scoring = ["accuracy", "precision", "recall", "f1"]

    cv_results = cross_validate(
        model, X_train, y_train,
        cv=skf,
        scoring=scoring,
        n_jobs=-1,          # Distribute parallel folds processing jobs across CPU resources
        return_train_score=True
    )

    print(f"\n  {cv}-Fold Cross-Validation on TRAIN:")
    print(f"  {'Metric':<12}  {'Train mean':>12}  {'Train std':>10}  {'Val mean':>10}  {'Val std':>10}")
    print(f"  {'-'*62}")
    # Compute statistical standard deviation boundaries across training loops
    for metric in scoring:
        tr_mean = np.mean(cv_results[f"train_{metric}"])
        tr_std  = np.std( cv_results[f"train_{metric}"])
        v_mean  = np.mean(cv_results[f"test_{metric}"])
        v_std   = np.std( cv_results[f"test_{metric}"])
        print(f"  {metric:<12}  {tr_mean:>12.4f}  {tr_std:>10.4f}  {v_mean:>10.4f}  {v_std:>10.4f}")


