# HELPER — COMPUTE FULL METRIC SET FOR ONE SPLIT
# =====================================================

def compute_metrics(model, X, y_true, split_name):
    """
    Returns a dict with all metrics for a given split.
    Handles both predict_proba and decision_function models.
    """
    # Generate discrete binary category predictions
    preds = model.predict(X)

    # Compute foundational supervised classification performance indicators
    acc  = accuracy_score(y_true, preds)
    prec = precision_score(y_true, preds, zero_division=0)
    rec  = recall_score(y_true, preds, zero_division=0)
    f1   = f1_score(y_true, preds, zero_division=0)

    # Safe evaluation of ROC-AUC score to handle architectural discrepancies natively
    try:
        # Logistic Regression and Naive Bayes provide class probability arrays
        if hasattr(model, "predict_proba"):
            scores = model.predict_proba(X)[:, 1]
        # LinearSVC provides a continuous raw distance score from the hyper-plane
        else:
            scores = model.decision_function(X)
        auc = roc_auc_score(y_true, scores)
    except Exception:
        auc = None

    return {
        "split"    : split_name,
        "accuracy" : round(acc,  4),
        "precision": round(prec, 4),
        "recall"   : round(rec,  4),
        "f1"       : round(f1,   4),
        "roc_auc"  : round(auc,  4) if auc is not None else None
    }


def print_metrics(metrics, model_name):
    """Prints out parsed metric values cleanly to the system standard output."""
    print(f"\n  {'Metric':<12}  {metrics['split']}")
    print(f"  {'-'*30}")
    for key in ["accuracy", "precision", "recall", "f1", "roc_auc"]:
        val = metrics[key]
        print(f"  {key:<12}  {val if val is not None else 'N/A'}")


def evaluate_both_splits(model, model_name):
    """
    Evaluates on TRAIN and TEST, prints both, prints
    classification report for test, and returns both dicts.
    """
    train_m = compute_metrics(model, X_train, y_train, "TRAIN")
    test_m  = compute_metrics(model, X_test,  y_test,  "TEST")

    print(f"\n{'='*60}")
    print(f"  {model_name}")
    print(f"{'='*60}")

    # Parse and display a side-by-side performance validation table
    print(f"\n  {'Metric':<12}  {'TRAIN':>10}  {'TEST':>10}  {'Overfit?':>10}")
    print(f"  {'-'*50}")
    for key in ["accuracy", "precision", "recall", "f1", "roc_auc"]:
        tr  = train_m[key]
        te  = test_m[key]
        if tr is not None and te is not None:
            # Track generalization variance drop metrics
            gap  = round(tr - te, 4)
            flag = " ⚠ overfit" if gap > 0.05 else ""
            print(f"  {key:<12}  {tr:>10}  {te:>10}  {gap:>+8.4f}{flag}")
        else:
            print(f"  {key:<12}  {'N/A':>10}  {'N/A':>10}")

    print(f"\n  Classification Report (TEST):")
    preds = model.predict(X_test)
    # Generate complete per-class breakdowns including target support counts
    report = classification_report(
        y_test, preds,
        target_names=["Fake (0)", "Real (1)"],
        digits=4
    )
    for line in report.splitlines():
        print(f"    {line}")

    return train_m, test_m


# =====================================================
# SAVE CONFUSION MATRIX PLOT
# =====================================================

def save_confusion_matrix(model, model_name):
    """Generates and saves scaled Seaborn heatmaps for the confusion matrix."""
    preds = model.predict(X_test)
    cm    = confusion_matrix(y_test, preds)

    fig, ax = plt.subplots(figsize=(5, 4))
    sns.heatmap(
        cm, annot=True, fmt="d", cmap="Blues", ax=ax,
        xticklabels=["Fake", "Real"],
        yticklabels=["Fake", "Real"]
    )
    ax.set_title(f"{model_name}\nConfusion Matrix (Test)")
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    plt.tight_layout()

    # Unified filename string parsing logic to map pipeline conventions
    filename = "results/" + model_name.lower().replace(" ", "_") + "_cm.png"
    plt.savefig(filename, dpi=150)
    plt.close()


